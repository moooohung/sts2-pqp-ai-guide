#[cfg(test)]
const TOKEN_COMBAT: u16 = 2;
#[cfg(test)]
const TOKEN_STRIKE: u16 = 16;

#[cfg(test)]
mod tests {
    use super::{choice_purpose_id, kind_id, token_id};
    #[test]
    fn frozen_contract_ids_are_stable() {
        assert_eq!(kind_id("global"), Some(2));
        assert_eq!(kind_id("candidate"), Some(15));
        assert_eq!(token_id("phase", "COMBAT"), Some(super::TOKEN_COMBAT));
        assert_eq!(
            token_id("card_id", "STRIKE_IRONCLAD"),
            Some(super::TOKEN_STRIKE)
        );
        assert_eq!(choice_purpose_id("none"), Some(0));
        assert_eq!(token_id("not-a-namespace", "anything"), None);
    }
}
